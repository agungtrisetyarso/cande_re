#!/usr/bin/env python3
"""
Self-check of the reproducibility package. Uses NumPy and SciPy only and imports none of the
other scripts, so it is an independent path to the headline numbers.

  A  rebuilds both plants from benchmarks/*.json and checks the model assumptions
     (compartmental matrix, conservation, positive steady state);
  B  recomputes headline numbers from those files and the design matrices in designs/ and
     compares them with the values generated by the experiment scripts and printed in the paper;
  C  compares every generated macro with the reference copy in expected/ (the values of the
     submitted manuscript) and checks that every macro used in main.tex is defined.

Exit status 0 if and only if every check passes.
"""
import glob, itertools, json, os, re, sys
from fractions import Fraction
import numpy as np
from scipy.optimize import linprog

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
p = lambda *a: os.path.join(ROOT, *a)
fails = []; n_checks = 0


def check(name, ok, detail=""):
    global n_checks; n_checks += 1
    print(("  ok    " if ok else "  FAIL  ") + name + (("   [" + detail + "]") if detail else ""))
    if not ok: fails.append(name)


def macros(path):
    out = {}
    for m in re.finditer(r"\\newcommand\{\\(\w+)\}\{((?:[^{}]|\{[^{}]*\})*)\}", open(path).read(), re.S):
        out[m.group(1)] = m.group(2)
    return out


def load(name):
    d = json.load(open(p("benchmarks", name + ".json")))
    K = np.array(d["K"]); f = np.array(d["f"]); edges = [tuple(e) for e in d["edges_tail_head"]]
    org = [tuple(e) for e in d["organic_stream_source_sink"]]
    B = np.zeros((len(f), len(edges)))
    for e, (i, j) in enumerate(edges): B[i, e] = -1; B[j, e] = 1
    mbar = np.linalg.solve(K, f)
    return dict(d=d, K=K, f=f, edges=edges, org=org, B=B, mbar=mbar, N=len(f))


def girth_and_cycles(N, edges):
    """Girth (inf for a forest) and cyclomatic number of the undirected unmeasured graph."""
    adj = {i: set() for i in range(N)}
    for i, j in edges: adj[i].add(j); adj[j].add(i)
    comp, seen = 0, set()
    for s in range(N):
        if s in seen: continue
        comp += 1; stack = [s]; seen.add(s)
        while stack:
            u = stack.pop()
            for v in adj[u]:
                if v not in seen: seen.add(v); stack.append(v)
    g = float("inf")
    for s in range(N):                                   # breadth-first search from every node
        dist = {s: 0}; par = {s: -1}; q = [s]
        for u in q:
            for v in adj[u]:
                if v not in dist: dist[v] = dist[u] + 1; par[v] = u; q.append(v)
                elif par[u] != v: g = min(g, dist[u] + dist[v] + 1)
    return g, len(edges) - N + comp


def exact_1_identifying(H, edges):
    """Exact (rational) test: every signature column non-zero and no two columns parallel."""
    Hf = [[Fraction(x).limit_denominator(10**9) for x in row] for row in H]
    cols = [tuple(r[j] - r[i] for r in Hf) for (i, j) in edges]
    if any(all(x == 0 for x in c) for c in cols): return False
    for a, b in itertools.combinations(cols, 2):
        if all(a[r] * b[s] == a[s] * b[r] for r in range(len(a)) for s in range(r + 1, len(a))): return False
    return True


print("A. Benchmarks rebuilt from benchmarks/*.json")
P, R = load("P"), load("R")
for nm, pl in (("P", P), ("R", R)):
    K = pl["K"]; off = K - np.diag(np.diag(K))
    check(f"{nm}: off-diagonal entries of -K non-negative (compartmental)", (off <= 1e-15).all())
    check(f"{nm}: column sums of K non-negative (outflow to the environment)", (K.sum(0) >= -1e-12).all())
    check(f"{nm}: steady state positive", (pl["mbar"] > 0).all())
    out = K.sum(0) @ pl["mbar"]
    check(f"{nm}: overall balance, feed in = product out", abs(out - pl["f"].sum()) < 1e-9 * pl["f"].sum(),
          f"{out:.6g} vs {pl['f'].sum():.6g}")
    # the organic stream behind edge e is the flux a_e * m_src; check that it is a stream of the model
    check(f"{nm}: every monitored edge carries a stream of the model",
          all(-K[snk, src] > 0 for (src, snk) in pl["org"]))

print("B. Headline numbers recomputed from the data files")
M = {}
for f_ in sorted(glob.glob(p("generated", "numbers*.tex"))): M.update(macros(f_))
res = json.load(open(p("generated", "results.json"))); res4 = json.load(open(p("generated", "results_rev4.json")))

check("P: number of stages and of unmeasured edges", P["N"] == res["N"] and len(P["edges"]) == int(M["nE"]))
check("P: steady inventories equal those of cascade_instrumentation.py",
      np.allclose([P["mbar"].min(), P["mbar"].max(), P["mbar"].mean()],
                  [res["mbar_min"], res["mbar_max"], res["mbar_mean"]], rtol=1e-10))
aP = np.array([-P["K"][snk, src] for (src, snk) in P["org"]])
trafficP = aP * np.array([P["mbar"][src] for (src, _) in P["org"]])
check("P: edge traffic equals that of cascade_instrumentation.py", np.allclose(trafficP, res["traffic"], rtol=1e-10))
check("P: fastest rate lambda", abs(np.diag(P["K"]).max() - res["lam"]) < 1e-12 and M["nLam"] == f"{np.diag(P['K']).max():.2f}")
g, beta = girth_and_cycles(P["N"], P["edges"])
check("P: unmeasured graph is a tree (no cycle, infinite girth)", beta == 0 and g == float("inf"))
g, beta = girth_and_cycles(R["N"], R["edges"])
check("R: unmeasured graph is one cycle of length 18 (Proposition on the closed loop)", beta == 1 and g == 18)

# lightest fractional vertex cover of the unmeasured edges, weights = steady inventories (sensitivity-budget law)
A = np.zeros((len(P["edges"]), P["N"]))
for e, (i, j) in enumerate(P["edges"]): A[e, i] = A[e, j] = -1
lp = linprog(P["mbar"], A_ub=A, b_ub=-np.ones(len(P["edges"])), bounds=(0, 1), method="highs")
check("P: lightest covering inventory M* and total inventory (Table of the law)",
      M["nLawMstar"] == f"{lp.fun:.2f}" and M["nLawMtot"] == f"{P['mbar'].sum():.2f}",
      f"M* = {lp.fun:.4f}, total = {P['mbar'].sum():.4f}")

for nm, pl in (("P", P), ("R", R)):
    Dc = np.array(pl["d"]["distribution_coefficient"]); ups = np.array(pl["d"]["organic_volume_fraction"])
    check(f"{nm}: phase-sensitivity factors (Lemma on the aliquot of dispersion)",
          np.allclose((Dc - 1) / (1 + ups * (Dc - 1)), res4["phase_factor"][nm], rtol=1e-12))
check("R: fastest stage turnover time, min", M["nRingLamInv"] == f"{1 / np.diag(R['K']).max():.0f}")
conc = R["mbar"][:15] / 600.0
check("R: Nd concentration range of the loaded stages, g/L",
      M["nRingConcMin"] == f"{conc.min():.0f}" and M["nRingConcMax"] == f"{conc.max():.0f}", f"{conc.min():.2f} to {conc.max():.2f}")
check("R: mean stage inventory, g", M["nRingInvMean"] == f"{R['mbar'].mean() / 1000:.1f}")

print("   design matrices in designs/")
for fn, pl in (("H_real_k4_N40", P), ("H_real_k8_N40", P), ("H_real_k12_N40", P), ("H_binary_k4_N40", P),
               ("H_block_k8_N40", P), ("H_real_k6_ring_n18", R), ("H_binary_ring_n18", R)):
    H = np.loadtxt(p("designs", fn + ".csv"), delimiter=",")
    T = H @ pl["B"]
    check(f"{fn}: shape matches the plant and every unmeasured edge is seen (detecting)",
          H.shape[1] == pl["N"] and (np.abs(T).max(0) > 1e-12).all())
    if fn != "H_block_k8_N40":
        check(f"{fn}: no two edge signatures parallel, exact arithmetic (structurally 1-identifying)",
              exact_1_identifying(H, pl["edges"]))
Hb = np.loadtxt(p("designs", "H_binary_ring_n18.csv"), delimiter=",")
loads = Hb @ R["mbar"] / 1000.0
rows = [r.split("&") for r in M["sheetrows"].strip().strip("%").split("\\\\") if "&" in r]
check("R: standing loads of the four binary pools equal the specification sheet",
      all(f"{loads[i]:.1f}" == rows[i][2].strip() for i in range(4)), ", ".join(f"{x:.1f}" for x in loads) + " g")
check("R: pooled stages of the specification sheet equal the design matrix",
      all([int(s) for s in rows[i][1].split(",")] == [j + 1 for j in np.flatnonzero(Hb[i])] for i in range(4)))

print("   Table of added streams (18-stage closed loop), recomputed from the graph definitions")
ring = [(i, i % 18 + 1) for i in range(1, 19)]                       # stages 1..18, node 0 = environment
cases = [ring, [e for e in ring if e != (18, 1)], ring + [(9, 0)], ring + [(5, 0), (12, 0)], ring + [(3, 14)], ring + [(14, 16)]]
grows = [r.split("&") for r in M["graphrows"].strip().strip("%").split("\\\\") if "&" in r]
for row, ed in zip(grows, cases):
    g, cyc = girth_and_cycles(19, ed)
    order = "any" if g == float("inf") else str(int(np.ceil(g / 2)) - 1)
    gs = "$\\infty$" if g == float("inf") else str(g)
    got = [str(len(ed)), str(cyc), gs, order]; want = [row[1].strip(), row[2].strip(), row[3].strip(), row[6].strip()]
    check(f"{row[0].strip()}: edges, cycles, girth, order", got == want, " ".join(got))

print("C. Generated values against the reference copy in expected/")
for f_ in sorted(glob.glob(p("expected", "numbers*.tex"))):
    ref = macros(f_); new = macros(p("generated", os.path.basename(f_)))
    diff = [k for k in ref if new.get(k) != ref[k]] + [k for k in new if k not in ref]
    check(f"{os.path.basename(f_)}: {len(ref)} values identical", not diff, ", ".join(diff[:6]))
tex = open(p("main.tex")).read() + open(p("supplement.tex")).read()
used = set(re.findall(r"\\(n[A-Z]\w*)", tex)) - {m for m in re.findall(r"\\newcommand\{\\(\w+)\}", tex)}
missing = sorted(u for u in used if u not in M)
check("every numerical macro used in main.tex and supplement.tex is generated by a script", not missing, ", ".join(missing[:6]))
import numpy, scipy, platform
print(f"   Python {platform.python_version()}, NumPy {numpy.__version__}, SciPy {scipy.__version__}")
print(f"\n{n_checks - len(fails)} of {n_checks} checks passed.")
sys.exit(1 if fails else 0)
